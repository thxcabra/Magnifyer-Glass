/**
 * Tiny i18n layer. Cookie-driven (no URL-segment routing) so it works
 * seamlessly across server + client components without restructuring the
 * app/ tree.
 *
 * Translation philosophy (from the project owner):
 *   "Traduzir aquilo que tenha um significado em portugues, por exemplo as
 *    posições, pontos por jogo. Nomes de jogadores, cidades, times, draft
 *    e essas coisas não precisam pois são termos que os brasileiros amantes
 *    de nba já sabem e conhecem."
 *
 * So we localize UI chrome, headings, button labels, stat names/definitions,
 * archetype names/descriptions, position names, and award names - but leave
 * player names, team names, city names, draft years, and standard stat
 * abbreviations (PPG, USG%, TS%) untouched because the Brazilian NBA audience
 * already speaks them natively.
 */

export const LOCALES = ["en", "pt-BR"] as const;
export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "en";
export const COOKIE_NAME = "magnifyer-locale";

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

