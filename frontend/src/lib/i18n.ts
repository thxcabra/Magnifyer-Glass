const DICTS: Record<Locale, Dict> = {
  "en": EN,
  "pt-BR": PT_BR,
};

/**
 * Look up a translation key, with English fallback and `{vars}` substitution.
 * Returns the key itself if nothing matches - so a missing key surfaces
 * obviously instead of silently rendering blank.
 */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const raw = DICTS[locale]?.[key] ?? DICTS.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
  );
}
